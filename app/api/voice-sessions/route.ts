import { createHash, timingSafeEqual } from "node:crypto";

import { getConfig } from "@/lib/server/config";
import { enforceRateLimit, jsonError, parseSessionId, PayloadTooLargeError, readJsonBody, tooLargeResponse } from "@/lib/server/http";
import { logError } from "@/lib/server/log";
import { getParentToken } from "@/lib/server/parent-token";
import { listVoiceSessions, saveVoiceSession } from "@/lib/server/voice-store";
import type { Conversation, ConversationMessage, SafetyEvent } from "@/types/conversation";

/**
 * Watch call records.
 *
 *   GET   → { store, sessions }  parent pages poll this
 *   POST  → { store }            the watch saves a finished call
 *
 * With VOICE_RECORD_STORE=local (default) nothing is stored here: both calls just say so and the
 * browser keeps the record itself. With "sqlite" both calls need the PARENT_API_TOKEN secret.
 */

const NO_STORE = { "Cache-Control": "no-store" };
const BODY_BYTES = 64 * 1024;
const MAX_MESSAGES = 60;
const MAX_EVENTS = 30;
const MAX_TEXT = 2_000;
const MAX_DURATION_SEC = 6 * 60 * 60;

export async function GET(request: Request) {
  const limited = enforceRateLimit(request, "records");
  if (limited) {
    return limited;
  }

  const { store, retentionDays } = getConfig().voiceRecords;
  if (store !== "sqlite") {
    // Parent pages keep their own copy, so they need the retention period to expire it too.
    return Response.json({ store: "local", sessions: [], retentionDays }, { headers: NO_STORE });
  }

  const denied = authorize(request);
  if (denied) {
    return denied;
  }

  try {
    return Response.json({ store, sessions: listVoiceSessions(), retentionDays }, { headers: NO_STORE });
  } catch (error) {
    logError("voice_sessions_list_failed", error);
    return jsonError("暫時讀不到通話紀錄。", 500);
  }
}

export async function POST(request: Request) {
  const limited = enforceRateLimit(request, "records");
  if (limited) {
    return limited;
  }

  const { store } = getConfig().voiceRecords;
  if (store !== "sqlite") {
    return Response.json({ store: "local" }, { headers: NO_STORE });
  }

  const denied = authorize(request);
  if (denied) {
    return denied;
  }

  let body: { conversation?: unknown } | null;
  try {
    body = await readJsonBody<{ conversation?: unknown }>(request, BODY_BYTES);
  } catch (error) {
    if (error instanceof PayloadTooLargeError) {
      return tooLargeResponse();
    }
    throw error;
  }

  const conversation = sanitizeConversation(body?.conversation);
  if (!conversation) {
    return jsonError("通話紀錄的格式不正確。", 400);
  }

  try {
    saveVoiceSession(conversation);
    return Response.json({ store }, { headers: NO_STORE });
  } catch (error) {
    logError("voice_sessions_save_failed", error);
    return jsonError("暫時無法儲存通話紀錄。", 500);
  }
}

function authorize(request: Request) {
  // Set by PARENT_API_TOKEN, or generated by the server and kept next to the database.
  const expected = getParentToken();
  if (!expected) {
    // Refusing is safer than serving a child's call history to anyone who finds the URL.
    return jsonError("伺服器無法取得家長端密碼，所以不提供通話紀錄。", 503);
  }
  const given = request.headers.get("x-parent-token") ?? "";
  if (!sameSecret(given, expected)) {
    return jsonError("沒有權限查看通話紀錄。", 401);
  }
  return null;
}

/** Compares digests so the check takes the same time wherever the first mismatch is. */
function sameSecret(given: string, expected: string) {
  const a = createHash("sha256").update(given).digest();
  const b = createHash("sha256").update(expected).digest();
  return timingSafeEqual(a, b);
}

function text(value: unknown, max = MAX_TEXT) {
  return typeof value === "string" ? value.slice(0, max) : "";
}

/**
 * Builds a clean watch-call record from untrusted JSON. Anything not listed here (extra fields,
 * images, other channels) is dropped on purpose.
 */
function sanitizeConversation(value: unknown): Conversation | null {
  if (!value || typeof value !== "object") {
    return null;
  }
  const raw = value as Record<string, unknown>;
  const id = parseSessionId(raw.id);
  if (!id || raw.category !== "voice" || raw.channel !== "watch" || !Array.isArray(raw.messages)) {
    return null;
  }

  const messages: ConversationMessage[] = [];
  for (const item of raw.messages.slice(0, MAX_MESSAGES)) {
    if (!item || typeof item !== "object") {
      continue;
    }
    const message = item as Record<string, unknown>;
    if (message.role !== "user" && message.role !== "assistant") {
      continue;
    }
    messages.push({
      role: message.role,
      content: text(message.content),
      ...(message.protected === true ? { protected: true } : {}),
      ...(message.blocked === true ? { blocked: true } : {}),
    });
  }
  if (messages.length === 0) {
    return null;
  }

  const events: SafetyEvent[] = [];
  for (const item of Array.isArray(raw.safetyEvents) ? raw.safetyEvents.slice(0, MAX_EVENTS) : []) {
    if (!item || typeof item !== "object") {
      continue;
    }
    const event = item as Record<string, unknown>;
    const eventId = parseSessionId(event.id);
    if (!eventId || (event.type !== "protected" && event.type !== "critical")) {
      continue;
    }
    events.push({
      id: eventId,
      type: event.type,
      createdAt: finiteTime(event.createdAt),
      category: "voice",
      ...(typeof event.maskedOriginal === "string" ? { maskedOriginal: text(event.maskedOriginal, 500) } : {}),
      ...(typeof event.safeText === "string" ? { safeText: text(event.safeText, 500) } : {}),
      read: false,
      acknowledged: false,
    });
  }

  const duration = Number(raw.durationSec);
  return {
    id,
    title: text(raw.title, 60) || "手錶語音通話",
    updatedAt: finiteTime(raw.updatedAt),
    category: "voice",
    channel: "watch",
    durationSec: Number.isFinite(duration) ? Math.min(MAX_DURATION_SEC, Math.max(0, Math.floor(duration))) : 0,
    messages,
    safetyEvents: events,
  };
}

function finiteTime(value: unknown) {
  const time = Number(value);
  const now = Date.now();
  // A clock that is wildly off would break "newest first"; fall back to the server's time.
  return Number.isFinite(time) && Math.abs(time - now) < 24 * 60 * 60 * 1000 ? Math.floor(time) : now;
}
