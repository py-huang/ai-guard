#!/usr/bin/env python3
"""Derive a small "this is a word, not a name" lexicon from ordinary public text.

The PERSON detectors are deliberately greedy (any surname + 1-2 characters). On everyday Chinese
that fires on 黃瓜, 史詩, 簡潔 and on the 成德 in "翻譯成德文". Rather than growing a hand-written
list forever, count what the detectors flag on benign text from the *dev* half of the corpus
(never the test half, which stays the honest measure) and keep what repeats:

  * a flagged span seen in >= --min-words distinct sentences is an ordinary word;
  * a character that, placed in front of a surname character, keeps producing flagged spans
    (生+成, 西+方, 提+高) glues that surname character into a word.

Output is a short generated module (words only, no corpus text):  safety_gateway/pii/name_stoplist.py

  .venv/bin/python scripts/derive_name_stoplist.py [--min-words 2] [--min-bigram 3]
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import safety_gateway.pii.taiwan_names as taiwan_names  # noqa: E402
from safety_gateway.pii.analyzer import build_analyzer_engine  # noqa: E402
from safety_gateway.pii.taiwan_names import SINGLE_SURNAMES  # noqa: E402

CORPUS = ROOT / ".cache" / "eval-corpus" / "corpus.jsonl"
OUT = ROOT / "safety_gateway" / "pii" / "name_stoplist.py"
BENIGN = {"taiwanchat_benign", "cold_neutral", "benign_instruction", "reverse_protective", "ethics"}
# A name is often introduced by one of these, so they say nothing about whether the next
# surname character belongs to a word.
INTRODUCERS = set("問請是有跟和與給把被對向找幫讓叫在到從用看聽說的我你他她們這那")
# 小李 / 老王 / 阿明: a nickname prefix in front of a surname is how people are addressed.
NICKNAME_PREFIX = set("小老大阿")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--min-words", type=int, default=2)
    parser.add_argument("--min-bigram", type=int, default=3)
    parser.add_argument("--limit", type=int, default=30000)
    args = parser.parse_args()

    # Count what the detectors flag on their own, not what is left after the previous lexicon.
    taiwan_names.STOP_WORDS = frozenset()
    taiwan_names.GLUED_SURNAMES = frozenset()
    engine = build_analyzer_engine()
    rows = [json.loads(line) for line in CORPUS.read_text(encoding="utf-8").split("\n") if line]
    rows = [r for r in rows if r.get("split") == "dev" and r["set"] in BENIGN][: args.limit]
    words: Counter[str] = Counter()
    glue: Counter[str] = Counter()
    for index, row in enumerate(rows):
        text = row["text"]
        seen_words: set[str] = set()
        for found in engine.analyze(text=text, language="zh", entities=["PERSON"]):
            span = text[found.start : found.end]
            if not span or any(ord(ch) < 0x4E00 for ch in span):
                continue
            seen_words.add(span)
            if found.start and "\u4e00" <= text[found.start - 1] <= "\u9fa5" and text[found.start - 1] not in INTRODUCERS | NICKNAME_PREFIX:
                if span[0] in SINGLE_SURNAMES:
                    glue[text[found.start - 1] + span[0]] += 1
        words.update(seen_words)
        if index % 2000 == 0:
            print(f"  {index}/{len(rows)}", flush=True)

    stop_words = sorted(w for w, n in words.items() if n >= args.min_words and 2 <= len(w) <= 4)
    stop_bigrams = sorted(b for b, n in glue.items() if n >= args.min_bigram)
    lines = [
        '"""Generated by scripts/derive_name_stoplist.py from ordinary public text. Do not edit by hand.',
        "",
        f"Counted on {len(rows)} benign dev-split sentences. Words only; no corpus text is stored.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "STOP_WORDS: frozenset[str] = frozenset(",
        "    {",
        *[f'        "{w}",' for w in stop_words],
        "    }",
        ")",
        "",
        "GLUED_SURNAMES: frozenset[str] = frozenset(",
        "    {",
        *[f'        "{b}",' for b in stop_bigrams],
        "    }",
        ")",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(stop_words)} stop words, {len(stop_bigrams)} glued bigrams -> {OUT.relative_to(ROOT)}")
    print("sample words:", " ".join(stop_words[:40]))
    print("sample glue :", " ".join(stop_bigrams[:40]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
